"""Code128 баркод (ISO/IEC 15417) — гадны сангүй, PDF-д вектор зураасаар зурахад.

  modules("513265") → [2, 1, 1, 2, 3, 2, …]  — зураас, зай ээлжилсэн өргөн (модулиар), зураасаар эхэлнэ.

Тоон хэсгийг Code C-ээр (2 цифр = 1 тэмдэгт) шахна: 6 оронтой код = 68 модуль. Үсэгтэй код
(«20Q3301») Code B-ээр, 4+ цифрийн дараалал гарвал Code C руу шилжинэ.
"""
from __future__ import annotations

# Утга 0–106 → 6 элемент (зураас/зай ээлжилсэн өргөн); 106 = Stop (7 элемент, 13 модуль)
_PATTERNS = (
    "212222", "222122", "222221", "121223", "121322", "131222", "122213", "122312", "132212", "221213",
    "221312", "231212", "112232", "122132", "122231", "113222", "123122", "123221", "223211", "221132",
    "221231", "213212", "223112", "312131", "311222", "321122", "321221", "312212", "322112", "322211",
    "212123", "212321", "232121", "111323", "131123", "131321", "112313", "132113", "132311", "211313",
    "231113", "231311", "112133", "112331", "132131", "113123", "113321", "133121", "313121", "211331",
    "231131", "213113", "213311", "213131", "311123", "311321", "331121", "312113", "312311", "332111",
    "314111", "221411", "431111", "111224", "111422", "121124", "121421", "141122", "141221", "112214",
    "112412", "122114", "122411", "142112", "142211", "241211", "221114", "413111", "241112", "134111",
    "111242", "121142", "121241", "114212", "124112", "124211", "411212", "421112", "421211", "212141",
    "214121", "412121", "111143", "111341", "131141", "114113", "114311", "411113", "411311", "113141",
    "114131", "311141", "411131", "211412", "211214", "211232", "2331112",
)
START_B, START_C, CODE_B, CODE_C, STOP = 104, 105, 100, 99, 106


def supported(s: str) -> bool:
    return bool(s) and all(32 <= ord(ch) <= 126 for ch in s)


def values(s: str) -> list[int]:
    """Тэмдэгтийн утгууд: start, өгөгдөл, шалгах тэмдэгт, stop."""
    if not supported(s):
        raise ValueError(f"Code128-д тохирохгүй утга: {s!r}")
    n = len(s)

    def run(i: int) -> int:
        j = i
        while j < n and s[j].isdigit():
            j += 1
        return j - i

    first = run(0)
    cur = "C" if first >= 4 or (first == n and n >= 2) else "B"
    out = [START_C if cur == "C" else START_B]
    i = 0
    while i < n:
        r = run(i)
        if cur == "C":
            if r >= 2:
                out.append(int(s[i:i + 2]))
                i += 2
            else:
                out.append(CODE_B)
                cur = "B"
        elif r >= 4:
            if r % 2:                                   # сондгой: эхний цифр B-ээр, үлдсэн хосууд C-ээр
                out.append(ord(s[i]) - 32)
                i += 1
            out.append(CODE_C)
            cur = "C"
        else:
            out.append(ord(s[i]) - 32)
            i += 1
    out.append((out[0] + sum(k * v for k, v in enumerate(out[1:], 1))) % 103)
    out.append(STOP)
    return out


def modules(s: str) -> list[int]:
    """Зураас/зай ээлжилсэн өргөнүүд (модулиар) — эхнийх нь зураас."""
    return [int(w) for v in values(s) for w in _PATTERNS[v]]
